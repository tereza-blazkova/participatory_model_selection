"""
Generate the LaTeX table for the equalized-recall threshold audit
(src/equalized_recall_audit.py).

One row per subgroup axis (sex, nationality, entry age relative to cohort): the Participatory
model's current single-threshold recall vs. the pooled recall that results
from equal-opportunity group-specific thresholds, the
difference in percentage points, the residual error-rate gap at the
equalized thresholds, and a 95% bootstrap CI on the difference.

Source: results/fairness/equalized_recall_audit.csv
  (produced by `python src/equalized_recall_audit.py`)

Run from project root:
    python src/make_equalized_recall_table.py
Writes: results/equalized_recall_table.tex
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).parent.parent))
from paths.paths import RESULTS_PATH
from src import disclosure
from src.display import feature_set_label, model_label

_SRC = RESULTS_PATH / "fairness" / "equalized_recall_audit.csv"
_OUT = RESULTS_PATH / "equalized_recall_table.tex"

_AXIS_ORDER = ["female", "danish_nationality", "older_for_cohort"]
_AXIS_LABEL = {
    "female":             "Female $-$ Male",
    "danish_nationality": "Non-Danish $-$ Danish",
    "older_for_cohort":   "Older $-$ younger for cohort",
}


def _fmt_recall(val: float) -> str:
    return f"{val:.3f}" if pd.notna(val) else "\N{EM DASH}"


def _fmt_recall_ci(val: float, lo: float, hi: float) -> str:
    if pd.isna(val):
        return "\N{EM DASH}"
    s = f"{val:.3f}"
    if pd.notna(lo) and pd.notna(hi):
        s += f" {{\\scriptsize[{lo:.3f},\\,{hi:.3f}]}}"
    return s


def _fmt_pp(val: float) -> str:
    return f"{val:+.1f}" if pd.notna(val) else "\N{EM DASH}"


def _fmt_pp_ci(lo: float, hi: float) -> str:
    if pd.isna(lo) or pd.isna(hi):
        return "\N{EM DASH}"
    return f"[{lo:+.1f}, {hi:+.1f}]"


def _fmt_share(val) -> str:
    return f"{val * 100:.1f}\\%" if pd.notna(val) else "\N{EM DASH}"


def _fmt_gap(val: float) -> str:
    """A gap in pp, unit in the column header."""
    return f"{val * 100:+.1f}" if pd.notna(val) else "\N{EM DASH}"


def _fmt_gap_change(before: str, after: str) -> str:
    """Single-threshold → equalized, one cell."""
    return f"{before} $\\to$ {after}"


def _axis_has_estimate(df: pd.DataFrame, col: str) -> bool:
    """A row exists for the axis, and it carries a value or a suppressed cell."""
    row = df[df["subgroup"] == col]
    if row.empty:
        return False
    row = row.iloc[0]
    return bool(pd.notna(row["single_threshold_recall"])
                or row.get("hidden_single_recall", False))


def _require_all_axes(df: pd.DataFrame) -> None:
    """
    Every axis in _AXIS_ORDER must have an estimate. A missing or empty axis
    would otherwise come out as a row of dashes, or not at all, so refuse.
    """
    missing = [c for c in _AXIS_ORDER if not _axis_has_estimate(df, c)]
    if missing:
        raise ValueError(
            f"equalized_recall_audit.csv has no estimate for {missing}. Check that "
            "enrollment_predictions.csv carries these columns, filled in, for the "
            "Participatory model (src/evaluation.py --merge refreshes them), then "
            "re-run src/equalized_recall_audit.py."
        )


def build_table(df: pd.DataFrame) -> str:
    _require_all_axes(df)
    lines: list[str] = []
    lines.append(r"% ── Equalized-recall threshold audit — auto-generated by make_equalized_recall_table.py")
    lines.append(r"% Requires: \usepackage{booktabs} in preamble.")
    lines.append("")
    lines.append(r"\begin{table}[h]")
    lines.append(r"\centering")
    lines.append(r"\footnotesize")
    lines.append(r"\begin{tabular}{lcccccc}")
    lines.append(r"\toprule")
    lines.append(
        r"Subgroup axis & Single-threshold & Equalized & Difference & "
        r"Flagged & Error-rate gap (pp) & 95\% CI on \\"
    )
    lines.append(
        r" & recall & recall & (pp) & share & single $\to$ equalized & difference (pp) \\"
    )
    lines.append(r"\midrule")

    for col in _AXIS_ORDER:
        row = df[df["subgroup"] == col].iloc[0]
        if "hidden_diff" not in row.index or "error_rate_gap_before" not in row.index:
            raise ValueError(
                "equalized_recall_audit.csv predates the current audit (no hidden_* or "
                "error_rate_gap_before column); re-run src/equalized_recall_audit.py first."
            )
        X = disclosure.SUPPRESSED_TEX
        h = lambda c: bool(row[c])   # noqa: E731
        cells = [
            _AXIS_LABEL[col],
            X if h("hidden_single_recall") else _fmt_recall(row["single_threshold_recall"]),
            X if h("hidden_equalized_recall") else _fmt_recall_ci(
                row["equalized_recall"], row["equalized_recall_lo"], row["equalized_recall_hi"]),
            X if h("hidden_diff") else _fmt_pp(row["diff_pp"]),
            X if h("hidden_flag_rate_after") else _fmt_share(row.get("flag_rate_after")),
            _fmt_gap_change(
                X if h("hidden_error_rate_gap_before") else _fmt_gap(row["error_rate_gap_before"]),
                X if h("hidden_error_rate_gap") else _fmt_gap(row["error_rate_gap_after"])),
            X if h("hidden_diff") else _fmt_pp_ci(row["diff_pp_lo"], row["diff_pp_hi"]),
        ]
        lines.append(" & ".join(cells) + r" \\")

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")

    model       = df["model"].iloc[0]
    feature_set = df["feature_set"].iloc[0]
    test_year   = df["test_year"].iloc[0]
    model_display   = model_label(model)
    feature_set_tex = feature_set_label(feature_set)
    budget = df["budget_rate"].iloc[0] if "budget_rate" in df.columns else float("nan")
    if pd.notna(budget):
        budget_sentence = (
            r"Equalization is constrained to the same intervention budget as the "
            r"single global threshold: the pooled flagged share may not exceed the "
            f"training enrollment-level dropout rate ({budget * 100:.1f}\\%), so the "
            r"common recall target is set as high as that budget allows. The reported "
            r"difference is therefore a recall change at a constant number "
            r"of flagged students, not recall bought by flagging more; ``Flagged share'' "
            r"reports the realized share. "
        )
    else:
        budget_sentence = (
            r"\emph{Unconstrained specification}: the flagged share is not capped, so a "
            r"positive difference reflects additional enrollments flagged rather than "
            r"a fairness-free gain --- read ``Flagged share'' alongside it. "
        )

    lines.append(
        r"\caption{\textbf{Equalized-recall threshold audit for the Participatory "
        f"model ({model_display}, feature set {feature_set_tex}, "
        f"test year {test_year})." + "} "
        r"For each subgroup axis, group-specific decision thresholds are set via "
        r"equal opportunity so recall is equalized across the "
        r"two groups (to within one student per group, since a threshold cannot split "
        r"students), holding the Participatory model's predicted probabilities fixed "
        r"(no retraining). " + budget_sentence +
        r"``Equalized recall'' is the resulting pooled enrollment-level "
        r"recall across the full population; ``Difference'' is equalized minus single-"
        r"threshold recall. ``Error-rate gap'' (comparison $-$ reference, in percentage "
        r"points of misclassification error) is shown at the single threshold and after "
        r"equalization; only recall is targeted, so this gap is not controlled and can "
        f"widen. The group thresholds are fitted on the {test_year} cohort itself; the 95\\% "
        r"bootstrap confidence intervals (1{,}000 iterations) in brackets hold them "
        r"fixed, so they do not include the uncertainty of fitting them. "
        r"Each axis uses the enrollments with a value on it, so the nationality row "
        r"leaves out students with unknown citizenship.}"
    )
    lines.append(r"\label{tab:equalized_recall_audit}")
    lines.append(r"\end{table}")

    return "\n".join(lines)


if __name__ == "__main__":
    if not _SRC.exists():
        raise FileNotFoundError(f"{_SRC} not found — run src/equalized_recall_audit.py first.")
    df = pd.read_csv(_SRC)
    content = build_table(df)
    _OUT.write_text(content, encoding="utf-8")
    print(f"Saved → {_OUT}")
